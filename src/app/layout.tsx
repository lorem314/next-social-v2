import { cookies } from "next/headers"
import type { Metadata } from "next"
import { Toaster } from "@/components/ui/sonner"
import jwt from "jsonwebtoken"
import { eq } from "drizzle-orm"

import { Header } from "@/components/layouts/header"
import { Footer } from "@/components/layouts/footer"
import { TRPCProvider } from "@/trpc/client"
import { GlobalContextProvider } from "@/components/global-context"
import { db } from "@/drizzle/db"
import { userTable } from "@/drizzle/schema"
import { config } from "@/config"

import "./globals.css"

const JWT_SECRET = process.env.JWT_SECRET as string

type JwtPayload = { userId: string; iat: number; exp: number }

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode
}>) {
  const awaitedCookies = await cookies()
  const refreshToken = awaitedCookies.get("refreshToken")?.value

  let user = null
  let accessToken = null

  if (refreshToken) {
    const payload = jwt.verify(refreshToken, JWT_SECRET) as JwtPayload

    const [result] = await db
      .select({
        id: userTable.id,
        email: userTable.email,
        name: userTable.name,
      })
      .from(userTable)
      .where(eq(userTable.id, payload.userId))

    user = result || null

    accessToken = jwt.sign({ userId: user.id }, JWT_SECRET, {
      expiresIn: config.ACCESS_TOKEN_EXP,
    })
  }

  // console.log("user", user)

  return (
    <html lang="en" className="">
      <body>
        <Toaster position="top-center" />
        <TRPCProvider>
          <GlobalContextProvider initialUser={user} accessToken={accessToken}>
            <div className="flex min-h-svh flex-col">
              <Header />
              <main className="my-12 grow">{children}</main>
              <Footer />
            </div>
          </GlobalContextProvider>
        </TRPCProvider>
      </body>
    </html>
  )
}

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
}
